#!/usr/bin/env bash
# Regenerate crates/subtoken-duckdb-sys/src/bindings.rs from the vendored
# DuckDB v2 headers, or with --check verify the committed file is exactly what
# regeneration produces.
#
# The output is committed so no ordinary build needs libclang. bindgen is a tool
# this script runs, not a Cargo dependency, and it is pinned: a different
# bindgen version writes different output, so the check would go red for the
# wrong reason. rustfmt, from the stable toolchain, also shapes the output and
# is not pinned: a rustfmt release that formats differently turns the check red,
# and the fix is to regenerate and commit.
#
# libclang: bindgen loads it at run time. On macOS it falls back to Xcode's
# Command Line Tools (this script sets LIBCLANG_PATH there if unset). On Linux
# the script points LIBCLANG_PATH at /usr/lib/llvm-$LIBCLANG_MAJOR/lib when
# that exists and the variable is unset, so a runner that ships several LLVM
# versions cannot switch libclang under the check. CI installs
# libclang-$LIBCLANG_MAJOR-dev, reading the major version from this file.
#
# Usage: scripts/regenerate_v2_bindings.sh [--check]
set -euo pipefail

BINDGEN_VERSION="0.73.2"
# The libclang major version used on Linux. Kept beside the bindgen pin so the
# pinned inputs are named, and enforced, in one place.
LIBCLANG_MAJOR="18"

root="$(cd "$(dirname "$0")/.." && pwd)"
crate="$root/crates/subtoken-duckdb-sys"
header="$crate/vendor/duckdb_extension_v2.h"
committed="$crate/src/bindings.rs"

mode="write"
case "${1:-}" in
  "") ;;
  --check) mode="check" ;;
  *) echo "usage: $0 [--check]" >&2; exit 2 ;;
esac

have="$(bindgen --version 2>/dev/null | awk '{print $2}' || true)"
if [ "$have" != "$BINDGEN_VERSION" ]; then
  echo "bindgen $BINDGEN_VERSION is required (found: ${have:-none}). Install it with:" >&2
  echo "  cargo install bindgen-cli --locked --version $BINDGEN_VERSION" >&2
  exit 1
fi

if [ -z "${LIBCLANG_PATH:-}" ] && [ -d "/usr/lib/llvm-$LIBCLANG_MAJOR/lib" ]; then
  export LIBCLANG_PATH="/usr/lib/llvm-$LIBCLANG_MAJOR/lib"
elif [ -z "${LIBCLANG_PATH:-}" ] && [ -d /Library/Developer/CommandLineTools/usr/lib ]; then
  export LIBCLANG_PATH=/Library/Developer/CommandLineTools/usr/lib
fi

tag="$(sed -n 's/^tag: *//p' "$crate/vendor/SOURCE.txt")"

out="$(mktemp)"
trap 'rm -f "$out" "$out.raw"' EXIT

# DUCKDB_V2_API_ALLOW_UNSTABLE=1: without it the header refuses to compile and
# every field of the function-pointer table is compiled out.
# -target is fixed so the output does not depend on the host platform.
bindgen "$header" \
  --allowlist-type 'duckdb_.*|idx_t' \
  --allowlist-var 'DUCKDB_.*' \
  --use-core \
  --ctypes-prefix core::ffi \
  --no-doc-comments \
  --no-include-path-detection \
  --rust-target 1.74 \
  -o "$out.raw" \
  -- -DDUCKDB_V2_API_ALLOW_UNSTABLE=1 -target x86_64-unknown-linux-gnu

{
  echo "// Generated by scripts/regenerate_v2_bindings.sh with bindgen $BINDGEN_VERSION"
  echo "// from DuckDB $tag's vendored v2 headers (vendor/SOURCE.txt). Do not edit."
  echo
  cat "$out.raw"
} | rustfmt --edition 2021 --emit stdout > "$out"

if [ "$mode" = "write" ]; then
  cp "$out" "$committed"
  echo "wrote $committed"
else
  if ! diff -u "$committed" "$out"; then
    echo "bindings.rs differs from a fresh regeneration; run scripts/regenerate_v2_bindings.sh" >&2
    exit 1
  fi
  echo "bindings.rs is up to date"
fi
